import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { createRenderServer, encryptConfig, decryptConfig } from './host-render.mjs';
import { createSqliteAccountStore } from './account-store.mjs';
import { hashPassword, verifyPassword } from './password-auth.mjs';

const secret = 'local-test-only-secret-with-32-or-more-characters';
const password = 'local-test-password-123';
const hash = await hashPassword(password);
assert.equal(await verifyPassword(password, hash), true);
assert.equal(await verifyPassword('incorrect-password', hash), false);
assert.notEqual(hash, await hashPassword(password));
assert.equal(hash.includes(password), false);
const config = { apiKey: 'not-a-real-key-used-for-local-tests', model: 'gemini-2.5-flash' };
const encrypted = encryptConfig(config, secret);
assert.deepEqual(decryptConfig(encrypted, secret), config);
assert.equal(decryptConfig(encrypted, secret + '-wrong'), null);

const filename = path.join(os.tmpdir(), 'dekel-account-test-' + randomUUID() + '.sqlite');
let store = await createSqliteAccountStore(filename);
const cookies = response => response.headers.getSetCookie().map(item => item.split(';')[0]).join('; ');
let server;
let base;
async function start(options = {}) {
  server = createRenderServer({ password, secret, hosted: false, accountStore: store, ...options });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  base = `http://127.0.0.1:${server.address().port}`;
}
const request = (url, options = {}) => fetch(base + url, { redirect: 'manual', ...options });
const post = (url, body, cookie) => request(url, { method: 'POST', headers: { origin: base, 'Content-Type': 'application/json', ...(cookie ? { cookie } : {}) }, body: JSON.stringify(body) });
try {
  await start();
  assert.equal((await request('/healthz')).status, 200);
  const home = await request('/');
  assert.equal(home.status, 200);
  assert.equal(home.headers.has('www-authenticate'), false);
  assert.equal((await request('/api/health')).status, 401);
  assert.equal((await request('/api/health', { headers: { 'oai-authenticated-user-id': 'spoofed' } })).status, 401);
  assert.equal((await (await request('/api/auth/session')).json()).registrationEnabled, true);
  assert.equal((await post('/api/auth/register', { username: 'alice', password: 'short' })).status, 400);
  assert.equal((await post('/api/auth/register', { username: 'short_rejected', password: '1234567' })).status, 400);
  assert.equal((await post('/api/auth/register', { username: 'eight_allowed', password: 'local8pw' })).status, 201);
  assert.equal((await post('/api/auth/login', { username: 'eight_allowed', password: 'local8pw' })).status, 200);
  assert.equal((await post('/api/auth/login', { username: 'eight_allowed', password: 'wrong' })).status, 401);
  assert.equal((await post('/api/auth/register', { username: 'dekel', password })).status, 400);
  const registered = await post('/api/auth/register', { username: 'Alice', password });
  assert.equal(registered.status, 201);
  const payload = await registered.json();
  assert.equal(payload.user.username, 'Alice');
  assert.equal(payload.user.password_hash, undefined);
  const aliceId = payload.user.id;
  let aliceCookie = cookies(registered);
  assert.equal((await post('/api/auth/register', { username: 'ALICE', password })).status, 409);
  const record = await store.find('alice');
  assert.ok(record.password_hash.startsWith('scrypt$'));
  assert.equal(record.password_hash.includes(password), false);
  assert.equal((await post('/api/auth/login', { username: 'Alice', password: 'wrong-password-value' })).status, 401);
  const logged = await post('/api/auth/login', { username: 'alice', password });
  assert.equal(logged.status, 200);
  aliceCookie = cookies(logged);
  const session = await (await request('/api/auth/session', { headers: { cookie: aliceCookie } })).json();
  assert.equal(session.user.id, aliceId);
  assert.equal(session.user.provider, 'password');
  const registeredBob = await post('/api/auth/register', { username: 'מעצב_חדש', password });
  assert.equal(registeredBob.status, 201);
  const bobId = (await registeredBob.json()).user.id;
  assert.notEqual(aliceId, bobId);
  const boundKey = encryptConfig({ userId: aliceId, keyConfig: config }, secret);
  const wrongKey = encryptConfig({ userId: bobId, keyConfig: config }, secret);
  assert.equal((await (await request('/api/health', { headers: { cookie: aliceCookie + '; __Host-dekel-config=' + boundKey } })).json()).hasApiKey, true);
  assert.equal((await (await request('/api/health', { headers: { cookie: aliceCookie + '; __Host-dekel-config=' + wrongKey } })).json()).hasApiKey, false);
  assert.equal((await request('/api/health', { headers: { cookie: aliceCookie, 'x-dekel-user-id': bobId } })).status, 409);
  assert.equal((await request('/api/auth/register', { method: 'POST', headers: { origin: 'https://untrusted.example' }, body: '{}' })).status, 403);
  const logout = await post('/api/auth/logout', {}, aliceCookie);
  assert.equal(logout.headers.getSetCookie().filter(item => item.includes('Max-Age=0')).length, 2);
  const owner = await post('/api/auth/owner', { password });
  assert.equal(owner.status, 200);
  assert.equal((await owner.json()).user.id, 'owner');
  const ownerViaLogin = await post('/api/auth/login', { username: 'dekel', password });
  assert.equal(ownerViaLogin.status, 200);
  assert.equal((await ownerViaLogin.json()).user.id, 'owner');
  await new Promise(resolve => server.close(resolve)); server = null;
  await store.close();
  store = await createSqliteAccountStore(filename);
  await start();
  const afterRestart = await post('/api/auth/login', { username: 'Alice', password });
  assert.equal(afterRestart.status, 200);
  assert.equal((await afterRestart.json()).user.id, aliceId);
  console.log('PASS: signup, persistent login after database restart, unique normalized usernames, salted password hashing, cookie isolation, CSRF, owner access and logout');
} finally {
  if (server) await new Promise(resolve => server.close(resolve));
  await store.close();
  await fs.rm(filename, { force: true });
}
